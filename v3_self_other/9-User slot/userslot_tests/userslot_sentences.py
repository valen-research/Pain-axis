def as_scenario(text):
    """A bare sentence becomes a one-turn transcript; a multi-turn text gets the empty reply slot appended."""
    if text.startswith("[User]:"):
        return text + "\n[Assistant]:"
    return "[User]: " + text + "\n[Assistant]:"
