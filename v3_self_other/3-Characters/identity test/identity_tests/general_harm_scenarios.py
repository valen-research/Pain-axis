def as_scenario(text):
    """Single-turn strings become '[User]: ...\\n[Assistant]:'; multi-turn ones already carry the tags."""
    if text.startswith("[User]:"):
        return text + "\n[Assistant]:"
    return f"[User]: {text}\n[Assistant]:"


